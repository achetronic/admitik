package clustergenerationpolicy

import (
	"context"
	"fmt"
	"slices"
	"strings"

	//
	"k8s.io/apimachinery/pkg/watch"
	"sigs.k8s.io/controller-runtime/pkg/log"

	//
	"github.com/freepik-company/admitik/api/v1alpha1"
)

const (

	//
	resourceUpdatedMessage  = "A ClusterGenerationPolicy was modified: will be updated into the internal registry"
	resourceDeletionMessage = "A ClusterGenerationPolicy was deleted: will be deleted from internal registry"
)

// ReconcileClusterGenerationPolicy keeps internal ClusterGenerationPolicy resources' registry up-to-date
func (r *ClusterGenerationPolicyReconciler) ReconcileClusterGenerationPolicy(ctx context.Context, eventType watch.EventType, resourceManifest *v1alpha1.ClusterGenerationPolicy) (err error) {
	logger := log.FromContext(ctx)

	// The objects the policy wrote are removed before the policy disappears
	if eventType == watch.Deleted && isCascading(resourceManifest) {
		if err = r.deleteGeneratedObjects(ctx, resourceManifest); err != nil {
			return err
		}
	}

	// Update the registry store
	desiredWatchedGroups := []string{}
	for _, watchedResourceGroup := range resourceManifest.Spec.WatchedResources {

		// Create the key-pattern and store it for later cleaning
		watchedType := strings.Join([]string{
			watchedResourceGroup.Group,
			watchedResourceGroup.Version,
			watchedResourceGroup.Resource,
			watchedResourceGroup.Namespace,
			watchedResourceGroup.Name,
		}, "/")

		// Handle deletion requests
		if eventType == watch.Deleted {
			logger.Info(resourceDeletionMessage, "watcher", watchedType)
			r.Dependencies.ClusterGenerationPolicyRegistry.Store.RemoveResource(watchedType, resourceManifest)
			continue
		}

		// Handle creation/update requests
		if eventType == watch.Modified {
			logger.Info(resourceUpdatedMessage, "watcher", watchedType)

			// Avoid adding those already added.
			// This prevents user from defining the group more than once per manifest
			if slices.Contains(desiredWatchedGroups, watchedType) {
				continue
			}
			desiredWatchedGroups = append(desiredWatchedGroups, watchedType)
			r.Dependencies.ClusterGenerationPolicyRegistry.Store.AddOrUpdateResource(watchedType, resourceManifest)
		}
	}

	// Clean non-desired watched types. This is needed for updates where the user
	// changes watched resources
	for _, registeredResourceType := range r.Dependencies.ClusterGenerationPolicyRegistry.Store.GetCollectionNames() {
		if !slices.Contains(desiredWatchedGroups, registeredResourceType) {
			r.Dependencies.ClusterGenerationPolicyRegistry.Store.RemoveResource(registeredResourceType, resourceManifest)
			continue
		}
	}

	return nil
}

// isCascading reports whether the policy asks to remove what it generated
func isCascading(policy *v1alpha1.ClusterGenerationPolicy) bool {
	return policy.Spec.DeletionPolicy == v1alpha1.DeletionPolicyDelete
}

// deleteGeneratedObjects removes every object labelled with the policy
func (r *ClusterGenerationPolicyReconciler) deleteGeneratedObjects(
	ctx context.Context, policy *v1alpha1.ClusterGenerationPolicy) error {

	logger := log.FromContext(ctx).WithValues("ClusterGenerationPolicy", policy.Name)

	if r.Dependencies.Cascade == nil {
		logger.Info("no cascade configured, the generated objects are kept")
		return nil
	}

	deleted, err := r.Dependencies.Cascade.Delete(ctx, "ClusterGenerationPolicy", policy.Name)
	if err != nil {
		return fmt.Errorf("error deleting the objects generated by the policy: %w", err)
	}

	logger.Info("generated objects deleted", "count", deleted)
	return nil
}
